const KIND_FALLBACK: Record<NodeKind, LucideIcon> = {
  intermediate: Layers,
  material: Box,
  raw: Container,
  tool: Wrench,
  consumable: Droplets,
  time: Clock,
};

export function iconFor(name: string, kind: NodeKind): LucideIcon {
  if (kind === 'time') return Clock;
  for (const [pattern, icon] of RULES) {
    if (pattern.test(name)) return icon;
  }
  return KIND_FALLBACK[kind] ?? Box;
}
