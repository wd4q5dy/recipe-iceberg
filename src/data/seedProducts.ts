export function findSeedProduct(query: string): SeedProduct | null {
  const q = query.trim().toLowerCase();
  if (!q) return null;
  const direct = SEED_PRODUCTS.find((p) => p.id === q || p.name.toLowerCase() === q);
  if (direct) return direct;
  const alias = ALIASES[q];
  if (alias) return SEED_PRODUCTS.find((p) => p.id === alias) ?? null;
  const partial = SEED_PRODUCTS.find((p) => p.name.toLowerCase().includes(q) || q.includes(p.id));
  return partial ?? null;
}

